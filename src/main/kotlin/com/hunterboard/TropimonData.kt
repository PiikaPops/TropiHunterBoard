package com.hunterboard

import com.google.gson.JsonParser
import net.fabricmc.loader.api.FabricLoader
import java.nio.file.Files
import java.nio.file.Path

/**
 * The Tropimon server's own spawn data, shipped inside the mod; its habitat data comes
 * from the relay instead (see [HabitatFeed]), the rest of this note applies to both.
 *
 * Cobblemon never sends these to the client. `CobblemonSpawnPools.load()` is called from
 * `registerDefaults()` and the pool object is not a `DataRegistry`, so it never appears in
 * the `sync()` loop; `HabitatPools.sync()` sends no packet either. Whatever the client
 * shows therefore comes from its own Cobblemon jar — which on Tropimon is wrong: 18 of the
 * 21 spawn files the server overrides differ from Cobblemon 1.8.4's, all 51 habitat pools
 * do (50 with a different species list), and 33 filler spawns do not exist in the jar at all.
 *
 * So the server's files travel with the mod and are laid over the base data once it is
 * read. `index.json` says how: **replace** for a file that also exists in Cobblemon — a
 * datapack file replaces its vanilla namesake whole, so the base entries that came from it
 * are dropped first — and **add** for a file Cobblemon does not have, whose spawns are
 * simply appended. That manifest is generated by diffing the modpack's own data (habitat
 * pools in `tropifurnitures`, spawn pools in `tropimod`) against the Cobblemon jar, not
 * guessed at runtime; regenerate it when the modpack updates. Herd files are installed
 * flat, since this folder is read without descending into `herds/`.
 */
object TropimonData {

    private const val ROOT = "assets/hunterboard/tropimon"

    /** One bundled data file. */
    class Entry(val fileName: String, val json: String, val replacesVanilla: Boolean)

    private var spawnFiles: List<Entry>? = null

    fun spawnPoolFiles(): List<Entry> {
        spawnFiles?.let { return it }
        val loaded = load("spawn_pool_world")
        spawnFiles = loaded
        return loaded
    }

    /**
     * The server's habitat pools. They are no longer shipped: [HabitatFeed] downloads them
     * from the relay, so they can follow the server between HunterBoard releases.
     */
    fun habitatPoolFiles(): List<Entry> = HabitatFeed.entries()

    /** True when the bundled dataset is present and readable at all. */
    fun isAvailable(): Boolean = spawnPoolFiles().isNotEmpty() || habitatPoolFiles().isNotEmpty()

    private fun modPath(relative: String): Path? = try {
        FabricLoader.getInstance().getModContainer(HunterBoard.MOD_ID)
            .flatMap { it.findPath(relative) }
            .orElse(null)
    } catch (_: Exception) { null }

    private fun load(folder: String): List<Entry> {
        val dir = modPath("$ROOT/$folder") ?: return emptyList()
        if (!try { Files.isDirectory(dir) } catch (_: Exception) { false }) return emptyList()

        val replace = manifestNames(folder)
        val out = mutableListOf<Entry>()
        try {
            Files.newDirectoryStream(dir).use { stream ->
                for (file in stream) {
                    val name = file.fileName.toString()
                    if (!name.endsWith(".json")) continue
                    try {
                        out.add(Entry(name, Files.readString(file), name in replace))
                    } catch (_: Exception) {}
                }
            }
        } catch (e: Exception) {
            HunterBoard.LOGGER.warn("Could not read the bundled Tropimon $folder: ${e.message}")
            return emptyList()
        }
        return out.sortedBy { it.fileName }
    }

    /** File names the manifest marks as replacing a Cobblemon file of the same name. */
    private fun manifestNames(folder: String): Set<String> {
        val path = modPath("$ROOT/index.json") ?: return emptySet()
        return try {
            val root = JsonParser.parseString(Files.readString(path)).asJsonObject
            val section = root.getAsJsonObject(folder) ?: return emptySet()
            section.getAsJsonArray("replace")?.mapNotNull {
                try { it.asString } catch (_: Exception) { null }
            }?.toSet() ?: emptySet()
        } catch (e: Exception) {
            HunterBoard.LOGGER.warn("Could not read the Tropimon data manifest: ${e.message}")
            emptySet()
        }
    }
}
